# ---------------------------------------------------------------- 工具函数
def _trend(key: str, parsed: dict) -> str:
    """判断某个指标在本次数据中的方向：high / low / normal / none。"""
    if key not in parsed or parsed[key] is None:
        return "none"
    return refs.metric_status(key, parsed[key], parsed.get("sex", "unknown"), parsed)


def _match_condition(when: dict, parsed: dict) -> bool:
    """检查诱因的触发条件是否被本次数据支持。"""
    for key, expect in when.items():
        st = _trend(key, parsed)
        if expect == "high" and st not in ("warning", "danger"):
            return False
        if expect == "low" and st != "low":
            return False
    return True


def metric_rule(key: str, parsed: dict = None):
    """返回某个指标的完整规则 + 诱因命中情况。"""
    rule = RULES.get(key)
    if not rule:
        return None
    parsed = parsed or {}
    causes = []
    for c in rule["causes"]:
        hit = bool(c.get("when")) and _match_condition(c["when"], parsed)
        causes.append({
            "text": c["text"],
            "tag": c["tag"],
            "hit": hit,
            "hint": "与你的数据吻合" if hit else None,
        })
    # 命中的诱因排到前面
    causes.sort(key=lambda x: not x["hit"])
    return {
        "key": key,
        "title": rule["title"],
        "summary": rule["summary"],
        "unit": refs.METRICS.get(key, {}).get("unit", ""),
        "causes": causes,
        "diseases": rule["diseases"],
        "checks": rule["checks"],
        "actions": rule["actions"],
    }


def matched_cross_rules(parsed: dict):
    """返回命中的组合规则（要求组合内所有指标都异常）。"""
    out = []
    for r in CROSS_RULES:
        if all(_trend(k, parsed) in ("warning", "danger") for k in r["keys"]):
            out.append({
                "keys": r["keys"],
                "title": r["title"],
                "detail": r["detail"],
                "level": r["level"],
                "names": [refs.METRICS[k]["name"] for k in r["keys"]],
            })
    return out


def fallback_rule(key: str, status: str) -> dict:
    """指标库已登记、但还没写专项规则的兜底条目：只给通用方向，不做具体病因推断。"""
