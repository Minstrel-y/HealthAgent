def build_insights(parsed: dict):
    """基于一次体检数据，产出「异常指标 → 可能诱因 / 关联疾病 / 建议」的推断清单。"""
    items = []
    for key in refs.METRICS:
        if key not in parsed or parsed[key] is None:
            continue
        status = refs.metric_status(key, parsed[key], parsed.get("sex", "unknown"), parsed)
        if status not in ("warning", "danger", "low"):
            continue
        rule = metric_rule(key, parsed) or fallback_rule(key, status)
        hits = [c for c in rule["causes"] if c["hit"]]
        items.append({
            "key": key,
            "name": refs.METRICS[key]["name"],
            "value": parsed[key],
            "unit": refs.METRICS[key]["unit"],
            "status": status,
            "status_label": refs.STATUS_LABEL[status],
            "summary": rule["summary"],
            "top_causes": (hits or rule["causes"])[:4],
            "hit_count": len(hits),
            "diseases": rule["diseases"][:4],
        })
    order = {"danger": 0, "warning": 1, "low": 2}
    items.sort(key=lambda x: order.get(x["status"], 3))
    return {
        "items": items,
        "cross": matched_cross_rules(parsed),
        "disclaimer": DISCLAIMER,
    }
